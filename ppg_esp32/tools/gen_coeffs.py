#!/usr/bin/env python3
"""
Generates ../filter_coeffs.h  (second-order-section filters for the ESP32).

Usage:  python gen_coeffs.py [fs]        (default fs = 125)
Every filter below is one entry from Table 2 of
Park et al. 2022, Front. Physiol. 12:808451, or from pyPPG.
Re-run with your real sampling rate and re-flash.
"""
import sys
import numpy as np
from scipy import signal

fs = float(sys.argv[1]) if len(sys.argv) > 1 else 125.0
nyq = fs / 2

# name, designer, order, band, kwargs, source
F = [
 ("CHEBY2_BP_0P5_12_O4",  "cheby2", 4, "bandpass", (0.5, 12),  dict(rs=20),
  "pyPPG default; Allen & Murray 2004 (4th order Chebyshev II best of 90 filters). rs=20 dB assumed"),
 ("BUTTER_BP_0P5_10_O4",  "butter", 4, "bandpass", (0.5, 10),  {},
  "Canac et al. 2019"),
 ("BUTTER_BP_0P5_50_O4",  "butter", 4, "bandpass", (0.5, 50),  {},
  "Pradhan et al. 2019 (needs fs > 100 Hz)"),
 ("CHEBY1_BP_0P5_16_O4",  "cheby1", 4, "bandpass", (0.5, 16),  dict(rp=0.5),
  "Ferro et al. 2015 (ripple 0.5 dB assumed - not given in paper)"),
 ("BUTTER_BP_0P5_5_O1",   "butter", 1, "bandpass", (0.5, 5),   {},
  "Sukor et al. 2011"),
 ("BUTTER_BP_0P2_10_O2",  "butter", 2, "bandpass", (0.2, 10),  {},
  "Liu et al. 2020b"),
 ("BUTTER_BP_0P4_10_O3",  "butter", 3, "bandpass", (0.4, 10),  {},
  "Papini et al. 2018"),
 ("BUTTER_HP_0P15_O2",    "butter", 2, "highpass", 0.15,       {},
  "Joseph et al. 2014 (0.15 Hz keeps pulse shape)"),
 ("BUTTER_LP_10_O2",      "butter", 2, "lowpass",  10,         {},
  "Liu et al. 2020a"),
 ("BUTTER_LP_15_O4",      "butter", 4, "lowpass",  15,         {},
  "Fischer et al. 2017"),
]

def design(kind, order, btype, band, kw):
    fn = {"butter": signal.butter, "cheby1": signal.cheby1, "cheby2": signal.cheby2}[kind]
    args = [order] + ([kw["rp"]] if "rp" in kw else []) + ([kw["rs"]] if "rs" in kw else [])
    return fn(*args, Wn=band, btype=btype, fs=fs, output="sos")

out = ["// AUTO-GENERATED by tools/gen_coeffs.py - do not edit by hand",
       f"// fs = {fs:g} Hz",
       "#pragma once", "",
       f"#define COEFF_FS {fs:.1f}f", ""]
names = []
for name, kind, order, btype, band, kw, src in F:
    hi = band[1] if isinstance(band, tuple) else band
    if hi >= nyq:
        out.append(f"// {name}: skipped, cutoff {hi} Hz >= Nyquist {nyq:g} Hz")
        continue
    sos = design(kind, order, btype, band, kw)
    out.append(f"// {name}: {src}")
    out.append(f"#define HAVE_{name} 1")
    out.append(f"static const int   {name}_N = {len(sos)};")
    out.append(f"static const float {name}[{len(sos)}][6] = {{")
    for s in sos:
        out.append("  {" + ", ".join(f"{v:.9e}f" for v in s) + "},")
    out.append("};\n")
    names.append(name)

open("../filter_coeffs.h", "w").write("\n".join(out))
print(f"wrote ../filter_coeffs.h  ({len(names)} filters, fs={fs:g})")
